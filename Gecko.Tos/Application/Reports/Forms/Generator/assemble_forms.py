"""Assemble the generated item lists of the 13 booking RDLs into one C# partial class (BookingFormItems.g.cs)."""
import re, os, sys
sys.stdout.reconfigure(encoding='utf-8')
S=os.path.dirname(os.path.abspath(__file__))
forms={
    'TMS.Booking.CY.CargoReleasePermitForm':'CyCargoReleasePermit',
    'TMS.Booking.CY.ContainerReleasePermit':'CyContainerReleasePermit',
    'TMS.Booking.CY.CustomPermit':'CyCustomsPermit',
    'TMS.Booking.CY.DeliveryOrder':'CyDeliveryOrder',
    'TMS.Booking.CYD.CargoReleasePermitForm':'CydCargoReleasePermit',
    'TMS.Booking.CYD.ContainerReleasePermit':'CydContainerReleasePermit',
    'TMS.Booking.CYD.CustomPermit':'CydCustomsPermit',
    'TMS.Booking.CYD.DeliveryOrder':'CydDeliveryOrder',
    'TMS.Booking.CFS.CargoReleasePermitForm(Format 1)':'CfsCargoReleasePermitFormat1',
    'TMS.Booking.CFS.CargoReleaseForm(Format3)':'CfsCargoReleaseFormat3',
    'TMS.Booking.CFS.ContainerReleasePermit':'CfsContainerReleasePermit',
    'TMS.Booking.CFS.DeliveryOrder':'CfsDeliveryOrder',
    'TMS.Booking.CFS.UnStuffingPermit':'CfsUnstuffingPermit',
}
letterheads=set()
out=['''// <auto-generated>
// The static report items of Vector's 13 booking RDLs (TMS_SCT/Tms.Reports/TMS.Booking.{CY,CYD,CFS}.*.rdl), generated from
// each RDL's body: every textbox, line and bordered rectangle at its own Top/Left/Width/Height (inches), its text or
// expression over the form's data (f), font size, alignment and borders. A letterhead that names the company prints the
// branch's invoicing company instead (falling back to the RDL's text). The tablixes are FormTable placeholders, written by
// hand in BookingForms.cs.
// </auto-generated>
using static Gecko.Tos.Application.Reports.Forms.FormLayout;

namespace Gecko.Tos.Application.Reports.Forms;

internal static partial class BookingForms
{''']
for rdl,name in forms.items():
    lines=open(os.path.join(S,'forms',rdl+'.cs.txt'),encoding='utf-8').read().splitlines()
    head=lines[0]
    out.append(f'    /// <summary>{rdl}.rdl — {head.split(": ",1)[1]}.</summary>')
    out.append(f'    private static List<FormItem> {name}Items(BookingForm f) =>')
    out.append('    [')
    for l in lines[1:]:
        if l.strip().startswith('// TABLE'):
            out.append(l); continue
        l=re.sub(r'(?i)COUNT\(f\.ContainerNo, "dstCustomForm"\)', 'f.ContainerCount', l)
        l=l.replace(' /* TODO */','')
        m=re.search(r'S\("(บริษัท สยามคอนเทนเนอร์[^"]*)"\)', l)
        if m and m.group(0)==re.search(r'T\([^,]+,[^,]+,[^,]+,[^,]+, (S\([^)]*\))',l).group(1):
            letterheads.add(m.group(1))
            l=l.replace(m.group(0), f'S(f.CompanyName ?? "{m.group(1)}")')
        if '/* TODO' in l: print('UNRESOLVED', rdl, l, file=sys.stderr)
        out.append(l)
    out.append('    ];')
    out.append('')
out[-1]='}'
open(sys.argv[1],'w',encoding='utf-8').write('\n'.join(out)+'\n')
print('letterheads:', letterheads)
